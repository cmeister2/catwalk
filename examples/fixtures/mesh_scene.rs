#[derive(Default)]
/// Authored Alembic property header and optional first-sample payload.
struct AbcProperty {
    /// Property name within its compound.
    name: String,
    /// Semicolon-separated schema or interpretation metadata.
    metadata: String,
    /// Nested properties for compound records.
    children: Vec<AbcProperty>,
    /// Optional POD type, component extent and encoded first-sample bytes.
    sample: Option<(u8, usize, Vec<u8>)>,
    /// Whether the sampled property uses array rather than scalar storage.
    array: bool,
}
impl AbcProperty {
    /// Create a compound property with schema metadata for supported geometry or transforms.
    fn compound(name: &str, children: Vec<Self>) -> Self {
        Self {
            name: name.into(),
            children,
            metadata: match name {
                ".geom" => "schema=AbcGeom_PolyMesh_v1;schemaBaseType=AbcGeom_GeomBase_v1".into(),
                ".xform" => "schema=AbcGeom_Xform_v3".into(),
                _ => String::new(),
            },
            ..Self::default()
        }
    }
    /// Encode authored numbers in the POD type required by the selected property name.
    #[allow(
        clippy::cast_possible_truncation,
        clippy::cast_sign_loss,
        reason = "Authored property values use valid small POD tags and indices; positions intentionally retain float32 Alembic storage."
    )]
    fn number(name: &str, extent: usize, values: &[f64]) -> Self {
        let (pod, bytes) = match name {
            ".ops" => (1, values.iter().map(|&v| v as u8).collect()),
            ".inherits" | "isNotConstantIdentity" => (0, values.iter().map(|&v| v as u8).collect()),
            "P" | "Cs" => (
                10,
                values
                    .iter()
                    .flat_map(|&v| (v as f32).to_le_bytes())
                    .collect(),
            ),
            ".faceCounts" | ".faceIndices" => (
                6,
                values
                    .iter()
                    .flat_map(|&v| (v as i32).to_le_bytes())
                    .collect(),
            ),
            _ => (11, values.iter().flat_map(|v| v.to_le_bytes()).collect()),
        };
        Self {
            name: name.into(),
            sample: Some((pod, extent, bytes)),
            array: matches!(name, "P" | "Cs" | ".faceCounts" | ".faceIndices"),
            metadata: match name {
                "P" => "geoScope=vtx;interpretation=point".into(),
                ".selfBnds" => "interpretation=box".into(),
                _ => String::new(),
            },
            ..Self::default()
        }
    }
}
/// Authored Alembic object with a schema, properties and child objects.
struct AbcObject {
    /// Object name within its parent.
    name: String,
    /// Schema token used to author geometry or transform object metadata.
    schema: String,
    /// Root compound property for the object.
    properties: AbcProperty,
    /// Child objects in deterministic archive order.
    children: Vec<AbcObject>,
}
/// Native Ogawa archive byte writer for the small authored Alembic examples.
struct Ogawa(Vec<u8>);
impl Ogawa {
    /// High-bit marker distinguishing native data pointers from group pointers.
    const DATA: u64 = 1 << 63;
    /// Append a length-prefixed native data block and return its tagged pointer.
    fn data(&mut self, payload: &[u8]) -> u64 {
        let offset = self.0.len() as u64;
        self.0.extend((payload.len() as u64).to_le_bytes());
        self.0.extend(payload);
        offset | Self::DATA
    }
    /// Append a native group of child pointers, using zero for an empty group.
    fn group(&mut self, children: &[u64]) -> u64 {
        if children.is_empty() {
            return 0;
        }
        let offset = self.0.len() as u64;
        self.0.extend((children.len() as u64).to_le_bytes());
        for id in children {
            self.0.extend(id.to_le_bytes());
        }
        offset
    }
    /// Recursively encode compound property headers and native scalar or array samples.
    #[allow(
        clippy::cast_possible_truncation,
        reason = "The authored archive has small property extents, object names and metadata lengths within u32 limits."
    )]
    fn property(&mut self, p: &AbcProperty) -> u64 {
        let mut children = Vec::new();
        let mut headers = Vec::new();
        for p in &p.children {
            let (kind, pod, extent, records) = if let Some((pod, extent, bytes)) = &p.sample {
                let scalar = !p.array;
                let mut record = vec![0; 16];
                record.extend(bytes);
                let id = self.data(&record);
                let records = if scalar {
                    vec![id]
                } else {
                    vec![id, Self::DATA]
                };
                (
                    if scalar { 1u32 } else { 2 },
                    *pod,
                    *extent,
                    self.group(&records),
                )
            } else {
                (0, 0, 0, self.property(p))
            };
            children.push(records);
            let info = kind
                | (2 << 2)
                | (u32::from(pod) << 4)
                | ((extent as u32) << 12)
                | (255 << 20)
                | if kind == 0 { 0 } else { 0x800 };
            headers.extend(info.to_le_bytes());
            if kind != 0 {
                headers.extend(1u32.to_le_bytes());
            }
            headers.extend((p.name.len() as u32).to_le_bytes());
            headers.extend(p.name.as_bytes());
            headers.extend((p.metadata.len() as u32).to_le_bytes());
            headers.extend(p.metadata.as_bytes());
        }
        if children.is_empty() {
            return 0;
        }
        children.push(self.data(&headers));
        self.group(&children)
    }
    /// Recursively encode object groups with names, schemas and child pointers.
    #[allow(
        clippy::cast_possible_truncation,
        reason = "The authored archive has small property extents, object names and metadata lengths within u32 limits."
    )]
    fn object(&mut self, o: &AbcObject) -> u64 {
        let mut children = vec![self.property(&o.properties)];
        let mut headers = Vec::new();
        for child in &o.children {
            children.push(self.object(child));
            headers.extend((child.name.len() as u32).to_le_bytes());
            headers.extend(child.name.as_bytes());
            headers.push(255);
            let metadata = if child.schema.is_empty() {
                String::new()
            } else if child.schema == "AbcGeom_Xform_v3" {
                format!(
                    "schema={};schemaObjTitle={}:.xform",
                    child.schema, child.schema
                )
            } else {
                format!(
                    "schema={};schemaBaseType=AbcGeom_GeomBase_v1;schemaObjTitle={}:.geom",
                    child.schema, child.schema
                )
            };
            headers.extend((metadata.len() as u32).to_le_bytes());
            headers.extend(metadata.as_bytes());
        }
        headers.resize(headers.len() + 32, 0);
        children.push(self.data(&headers));
        self.group(&children)
    }
    /// Encode a complete closed Ogawa archive with its default time-sampling table.
    fn archive(object: &AbcObject) -> Vec<u8> {
        let mut w = Self(b"Ogawa\xff\0\x01\0\0\0\0\0\0\0\0".to_vec());
        let version = w.data(&0u32.to_le_bytes());
        let release = w.data(&10803u32.to_le_bytes());
        let object = w.object(object);
        // Native archive time-sampling table: max sample count, period, stored
        // time count and time. Property headers use this default index zero.
        let mut times = 1u32.to_le_bytes().to_vec();
        times.extend(1f64.to_le_bytes());
        times.extend(1u32.to_le_bytes());
        times.extend(0f64.to_le_bytes());
        let times = w.data(&times);
        let root = w.group(&[version, release, object, Self::DATA, times, Self::DATA]);
        w.0[8..16].copy_from_slice(&root.to_le_bytes());
        w.0
    }
}
