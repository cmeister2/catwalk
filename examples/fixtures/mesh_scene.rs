/// Add an indexed quad at the requested depth and optional alternate UV set.
fn quad_mesh(g: &mut Gltf, z: f32, material: usize, uv1: bool) -> Value {
    let position = g.positions(&[[-1., -1., z], [1., -1., z], [1., 1., z], [-1., 1., z]]);
    let normal = float_accessor(g, "VEC3", &[[0., 0., 1.]; 4]);
    let uv = float_accessor(g, "VEC2", &[[0., 1.], [1., 1.], [1., 0.], [0., 0.]]);
    let indices = g.accessor(
        "SCALAR",
        5123,
        6,
        &[0u16, 1, 2, 0, 2, 3]
            .into_iter()
            .flat_map(u16::to_le_bytes)
            .collect::<Vec<_>>(),
        false,
    );
    let mut attributes = json!({"POSITION":position,"NORMAL":normal,"TEXCOORD_0":uv});
    if uv1 {
        let wrong = float_accessor(g, "VEC2", &[[0., 0.]; 4]);
        let selected = float_accessor(
            g,
            "VEC2",
            &[[-0.4, 1.75], [2.4, 1.75], [2.4, -0.25], [-0.4, -0.25]],
        );
        attributes["TEXCOORD_0"] = json!(wrong);
        attributes["TEXCOORD_1"] = json!(selected);
    }
    json!({"primitives":[{"attributes":attributes,"indices":indices,"material":material}]})
}

