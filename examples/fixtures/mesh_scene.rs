fn threeds() -> Vec<u8> {
    let mut positions = 4u16.to_le_bytes().to_vec();
    for p in POINTS {
        for v in p {
            positions.extend(v.to_le_bytes());
        }
    }
    let mut faces = 4u16.to_le_bytes().to_vec();
    for face in FACES {
        for i in face {
            faces.extend(i.to_le_bytes());
        }
        faces.extend(0u16.to_le_bytes());
    }
    let mut materials = Vec::new();
    for (i, c) in COLORS.iter().enumerate() {
        let name = format!("face{i}\0");
        let mut group = name.as_bytes().to_vec();
        group.extend(1u16.to_le_bytes());
        group.extend((i as u16).to_le_bytes());
        faces.extend(chunk(0x4130, &group));
        let mut material = chunk(0xa000, name.as_bytes());
        material.extend(chunk(0xa020, &chunk(0x0011, c)));
        materials.extend(chunk(0xafff, &material));
    }
    let mut mesh = chunk(0x4110, &positions);
    mesh.extend(chunk(0x4120, &faces));
    let mut object = b"tetra\0".to_vec();
    object.extend(chunk(0x4100, &mesh));
    let mut editor = chunk(0x4000, &object);
    editor.extend(materials);
    chunk(0x4d4d, &chunk(0x3d3d, &editor))
}
