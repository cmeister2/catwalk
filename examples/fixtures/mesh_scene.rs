    for v in [0.01f32, 0.01, 0.01, 0., 0., 0., 3., 0., 0., 0.] {
        bytes.extend(v.to_le_bytes());
    }
    for v in [1i32, 2, 2, 4, 4, 1, 0, 0] {
        bytes.extend(v.to_le_bytes());
    }
    bytes.extend(1f32.to_le_bytes());
    bytes.extend(0i32.to_le_bytes());
    bytes.extend([50, 100, 150, 200]);
    for _ in POINTS {
        for v in [0i32, 0, 0] {
            bytes.extend(v.to_le_bytes());
        }
    }
    for face in FACES {
        bytes.extend(1i32.to_le_bytes());
        for index in face {
            bytes.extend(i32::from(index).to_le_bytes());
        }
    }
    bytes.extend(0i32.to_le_bytes());
    bytes.extend([0, 0, 0, 0, 200, 160, 230, 0]);
    let mut name = [0; 16];
    name[..6].copy_from_slice(b"frame0");
