/// Append a floating point vector accessor in little-endian component order.
fn float_accessor<const N: usize>(g: &mut Gltf, kind: &str, values: &[[f32; N]]) -> usize {
    let bytes: Vec<_> = values
        .iter()
        .flatten()
        .flat_map(|v| v.to_le_bytes())
        .collect();
    g.accessor(kind, 5126, values.len(), &bytes, false)
}

/// Encode the authored four-color texture, optionally including four alpha levels.
fn authored_texture(mask: bool) -> Result<Vec<u8>> {
    let colors = [
        [240, 55, 40, if mask { 0 } else { 255 }],
        [40, 220, 65, if mask { 64 } else { 255 }],
        [45, 65, 230, if mask { 192 } else { 255 }],
        [245, 215, 40, 255],
    ];
    let image = image::RgbaImage::from_fn(8, 8, |x, y| {
        image::Rgba(colors[(x / 4 + 2 * (y / 4)) as usize])
    });
    let mut output = Cursor::new(Vec::new());
    image.write_to(&mut output, image::ImageFormat::Png)?;
    Ok(output.into_inner())
}

/// Append PNG bytes as a buffer-view image with its explicit MIME type.
fn image_in_buffer(g: &mut Gltf, bytes: &[u8]) {
    while !g.bytes.len().is_multiple_of(4) {
        g.bytes.push(0);
    }
    let offset = g.bytes.len();
    g.bytes.extend(bytes);
    let views = g.document["bufferViews"].as_array_mut().unwrap();
    let view = views.len();
    views.push(json!({"buffer":0,"byteOffset":offset,"byteLength":bytes.len()}));
    g.document["images"] = json!([{"bufferView":view,"mimeType":"image/png"}]);
}

