/// Write the shared tetrahedron in plain mesh formats and register wireframe examples.
#[allow(
    clippy::too_many_lines,
    clippy::cast_possible_truncation,
    reason = "The fixed four-face mesh is written in several encodings together; its binary face count fits u32."
)]
fn plain_meshes(f: &mut Fixtures<'_>) -> Result<()> {
    let mut ascii = String::from("solid authored_tetrahedron\n");
    for face in FACES {
        let n = normal(face);
        write!(
            ascii,
            "facet normal {} {} {}\nouter loop\n",
            n[0], n[1], n[2]
        )?;
        for index in face {
            let p = POINTS[index as usize];
            writeln!(ascii, "vertex {} {} {}", p[0], p[1], p[2])?;
        }
        ascii.push_str("endloop\nendfacet\n");
    }
    ascii.push_str("endsolid authored_tetrahedron\n");
    f.add(
        "stl-ascii-tetrahedron",
        "stl",
        "STL ASCII closed tetrahedron",
        ascii.as_bytes(),
    )?;
    let mut binary = vec![0; 80];
    let title = b"Catwalk authored binary mesh";
    binary[..title.len()].copy_from_slice(title);
    binary.extend((FACES.len() as u32).to_le_bytes());
    for face in FACES {
        for n in normal(face) {
            binary.extend(n.to_le_bytes());
        }
        for index in face {
            for v in POINTS[index as usize] {
                binary.extend(v.to_le_bytes());
            }
        }
        binary.extend(0u16.to_le_bytes());
    }
    f.add(
        "stl-binary-tetrahedron",
        "stl",
        "STL binary closed tetrahedron",
        &binary,
    )?;
    let mut obj =
        String::from("# Author-created tetrahedron\nmtllib obj-palette.mtl\no Tetrahedron\n");
    for p in POINTS {
        writeln!(obj, "v {} {} {}", p[0], p[1], p[2])?;
    }
    let mut mtl = String::new();
    for (i, face) in FACES.iter().enumerate() {
        write!(
            obj,
            "usemtl face{i}\nf {} {} {}\n",
            face[0] + 1,
            face[1] + 1,
            face[2] + 1
        )?;
        let c = COLORS[i].map(|v| f64::from(v) / 255.);
        write!(mtl, "newmtl face{i}\nKd {} {} {}\n\n", c[0], c[1], c[2])?;
    }
    f.resource("obj-palette.mtl", mtl.as_bytes())?;
    f.add(
        "obj-material-palette",
        "obj",
        "OBJ closed mesh with detached MTL palette",
        obj.as_bytes(),
    )?;
    wireframe_cases(f)?;
    let header = |encoding: &str| {
        format!(
            "ply\nformat {encoding} 1.0\ncomment Catwalk authored tetrahedron\nelement vertex 4\nproperty float x\nproperty float y\nproperty float z\nproperty uchar red\nproperty uchar green\nproperty uchar blue\nelement face 4\nproperty list uchar int vertex_indices\nend_header\n"
        )
    };
    let mut ply = header("ascii");
    for (p, c) in POINTS.iter().zip(COLORS) {
        writeln!(ply, "{} {} {} {} {} {}", p[0], p[1], p[2], c[0], c[1], c[2])?;
    }
    for face in FACES {
        writeln!(ply, "3 {} {} {}", face[0], face[1], face[2])?;
    }
    f.add(
        "ply-ascii-colors",
        "ply",
        "PLY ASCII colored vertices",
        ply.as_bytes(),
    )?;
    for big in [false, true] {
        let mut bytes = header(if big {
            "binary_big_endian"
        } else {
            "binary_little_endian"
        })
        .into_bytes();
        for (p, c) in POINTS.iter().zip(COLORS) {
            for v in p {
                bytes.extend(if big {
                    v.to_be_bytes()
                } else {
                    v.to_le_bytes()
                });
            }
            bytes.extend(c);
        }
        for face in FACES {
            bytes.push(3);
            for v in face {
                let v = i32::from(v);
                bytes.extend(if big {
                    v.to_be_bytes()
                } else {
                    v.to_le_bytes()
                });
            }
        }
        f.add(
            if big {
                "ply-binary-big-endian"
            } else {
                "ply-binary-little-endian"
            },
            "ply",
            if big {
                "PLY binary big endian colored mesh"
            } else {
                "PLY binary little endian colored mesh"
            },
            &bytes,
        )?;
    }
    let mut off = String::from("COFF\n4 4 6\n");
    for (p, c) in POINTS.iter().zip(COLORS) {
        writeln!(
            off,
            "{} {} {} {} {} {} 255",
            p[0], p[1], p[2], c[0], c[1], c[2]
        )?;
    }
    for face in FACES {
        writeln!(off, "3 {} {} {}", face[0], face[1], face[2])?;
    }
    f.add(
        "off-colored-tetrahedron",
        "off",
        "OFF vertex-colored closed tetrahedron",
        off.as_bytes(),
    )
}

/// Compute a normalized triangle normal for a face of the shared tetrahedron.
#[allow(
    clippy::cast_possible_truncation,
    reason = "Unit normals are finite components within f32 range and are intentionally stored as STL f32 components."
)]
fn normal(face: [u16; 3]) -> [f32; 3] {
    let [a, b, c] = face.map(|i| catwalk::scene::Vec3::from(POINTS[i as usize]));
    let n = (b - a).cross(c - a).normalized();
    [n.x as f32, n.y as f32, n.z as f32]
}

/// Authored glTF document paired with its accumulated binary buffer.
struct Gltf {
    /// JSON document containing resource, attribute and scene references.
    document: Value,
    /// Binary attribute and embedded image bytes in buffer-view order.
    bytes: Vec<u8>,
}
impl Gltf {
    /// Create an empty glTF 2 document with one selected root scene.
    fn new() -> Self {
        Self {
            document: json!({"asset":{"version":"2.0","generator":"Catwalk authored fixtures"},"buffers":[],"bufferViews":[],"accessors":[],"meshes":[],"nodes":[],"scenes":[{"nodes":[0]}],"scene":0}),
            bytes: Vec::new(),
        }
    }
    /// Append an aligned buffer view and accessor describing authored attribute bytes.
    fn accessor(
        &mut self,
        kind: &str,
        component: u32,
        count: usize,
        bytes: &[u8],
        normalized: bool,
    ) -> usize {
        while !self.bytes.len().is_multiple_of(4) {
            self.bytes.push(0);
        }
        let offset = self.bytes.len();
        self.bytes.extend(bytes);
        let views = self.document["bufferViews"].as_array_mut().unwrap();
        let view = views.len();
        views.push(json!({"buffer":0,"byteOffset":offset,"byteLength":bytes.len()}));
        let accessors = self.document["accessors"].as_array_mut().unwrap();
        let index = accessors.len();
        accessors
            .push(json!({"bufferView":view,"componentType":component,"type":kind,"count":count}));
        if normalized {
            accessors[index]["normalized"] = json!(true);
        }
        index
    }
    /// Append floating point positions and author their independent component bounds.
    fn positions(&mut self, points: &[[f32; 3]]) -> usize {
        let bytes: Vec<_> = points
            .iter()
            .flatten()
            .flat_map(|v| v.to_le_bytes())
            .collect();
        let index = self.accessor("VEC3", 5126, points.len(), &bytes, false);
        self.document["accessors"][index]["min"] = json!(
            (0..3)
                .map(|i| points.iter().map(|p| p[i]).fold(f32::INFINITY, f32::min))
                .collect::<Vec<_>>()
        );
        self.document["accessors"][index]["max"] = json!(
            (0..3)
                .map(|i| points
                    .iter()
                    .map(|p| p[i])
                    .fold(f32::NEG_INFINITY, f32::max))
                .collect::<Vec<_>>()
        );
        index
    }
    /// Serialize the document with its binary buffer embedded as a base64 data URI.
    fn embedded(&mut self) -> Result<Vec<u8>> {
        self.document["buffers"] = json!([{"byteLength":self.bytes.len(),"uri":format!("data:application/octet-stream;base64,{}",STANDARD.encode(&self.bytes))}]);
        Ok(serde_json::to_vec_pretty(&self.document)?)
    }
    /// Serialize the document and binary buffer into a native GLB container.
    fn glb(&mut self) -> Result<Vec<u8>> {
        self.document["buffers"] = json!([{"byteLength":self.bytes.len()}]);
        glb(&self.document, &self.bytes)
    }
}
/// Encode padded JSON and binary chunks with the native GLB header and chunk types.
#[allow(
    clippy::cast_possible_truncation,
    reason = "The small authored fixture buffers and their padded container sizes are below u32 limits."
)]
fn glb(document: &Value, binary: &[u8]) -> Result<Vec<u8>> {
    let mut json = serde_json::to_vec(document)?;
    while !json.len().is_multiple_of(4) {
        json.push(b' ');
    }
    let mut binary = binary.to_vec();
    while !binary.len().is_multiple_of(4) {
        binary.push(0);
    }
    let mut bytes = Vec::new();
    for n in [
        0x4654_6c67_u32,
        2,
        (28 + json.len() + binary.len()) as u32,
        json.len() as u32,
        0x4e4f_534a,
    ] {
        bytes.extend(n.to_le_bytes());
    }
    bytes.extend(json);
    bytes.extend((binary.len() as u32).to_le_bytes());
    bytes.extend(0x004e_4942_u32.to_le_bytes());
    bytes.extend(binary);
    Ok(bytes)
}
/// Build the colored tetrahedron glTF with a nonidentity node rotation.
fn tetra_gltf() -> Gltf {
    let mut g = Gltf::new();
    let position = g.positions(&POINTS);
    let index_bytes: Vec<_> = FACES
        .iter()
        .flatten()
        .flat_map(|v| v.to_le_bytes())
        .collect();
    let indices = g.accessor("SCALAR", 5123, 12, &index_bytes, false);
    let colors: Vec<_> = COLORS.iter().flatten().copied().collect();
    let color = g.accessor("VEC3", 5121, 4, &colors, true);
    g.document["meshes"] = json!([{"primitives":[{"attributes":{"POSITION":position,"COLOR_0":color},"indices":indices}]}]);
    g.document["nodes"] =
        json!([{"mesh":0,"rotation":[0.,0.173_648_177_666_930_33,0.,0.984_807_753_012_208]}]);
    g
}
